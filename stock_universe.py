# Convenience helper for stock metadata
from market_utils import get_market_benchmark, is_indian_ticker, format_currency


def get_stock_metadata(ticker: str):
    """Returns complete metadata for a ticker in the universe."""
    clean_ticker = str(ticker).strip().upper()
    company_name = STOCK_UNIVERSE.get(clean_ticker, clean_ticker)
    benchmark_info = get_market_benchmark(clean_ticker)
    return {
        "ticker": clean_ticker,
        "company_name": company_name,
        **benchmark_info
    }

